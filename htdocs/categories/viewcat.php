        $incremento = GETPOST('percent_incremento', 'int', '2');

        if ($incremento != '') {
			require_once DOL_DOCUMENT_ROOT . '/product/class/product.class.php';
			require_once DOL_DOCUMENT_ROOT . '/fourn/class/fournisseur.product.class.php';
            $products = $object->getObjectsInCateg("product");


            $success = 0;
            $fail = 0;
			$error = "";
            foreach ($products as $product) {

				$prod = new Product($db);
				$prod->fetch($product->id);
				$cost_price = $prod->cost_price;
				$prod->cost_price_sucursal = $cost_price + ($cost_price * ($incremento / 100));
				$res_update = $prod->update($product->id, $user);
				if ($res_update > 0) {
					$success++;
				} else {
					$fail++;
					$error .= $prod->ref . ", ";
				}
            }
			if($fail > 0){
				setEventMessage($langs->trans("No tienen precio de Compra: ". $error),  'errors');
				$action = 'set_ganancia';
			}else{
				setEventMessage($langs->trans("RecordsSaved", $success), $success > 0 ? 'mesgs' : 'succes');
				$action = '';
			}
        }
        else {
            setEventMessage($langs->trans('Incremento Requerio'), 'errors');
            $action = 'set_ganancia';
        }
    }
