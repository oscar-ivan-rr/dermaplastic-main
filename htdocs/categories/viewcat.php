	$cancel = GETPOST('cancel', 'alpha');

	if (!$cancel) {
		$discount = GETPOST('percent_discount', 'int', '2');

		$date_lim_discount = $date_lim_discountyear ? $date_lim_discountyear . "-" . $date_lim_discountmonth . "-" . $date_lim_discountday : '';
		$current_date = $date_lim_discountyear ? date('Y-m-d') : '';
	
		if ($discount == '') {
			setEventMessage($langs->trans('DiscountRequired'), 'errors');
			$action = 'set_discount';
		} elseif ($discount < 0) {
			setEventMessage('El descuento tiene que tener un valor positivo.', 'errors');
			$action = 'set_discount';
		} elseif (strtotime($date_lim_discount) < strtotime($current_date)) {
			setEventMessage('La fecha de vencimiento del descuento temporal es anterior a la fecha actual.', 'errors');
			$action = 'set_discount';
		} else {
			require_once DOL_DOCUMENT_ROOT . '/product/class/product.class.php';
			$products = $object->getObjectsInCateg("product");

			// Multiplicado de precio
			$decimal = (1 - $discount / 100);
			$success = 0;
			foreach ($products as $product) {
				// Descuento aplicado sobre producto
				if($product->desc_max > 0){
					if ($product->setDiscount($decimal, $date_lim_discountday, $date_lim_discountmonth, $date_lim_discountyear) > 0)
						$success++;
				}
			}
			setEventMessage($langs->trans("RecordsSaved", $success), $success > 0 ? 'mesgs' : 'warnings');
			$action = '';
		}
	}
